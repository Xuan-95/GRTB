#!/bin/bash

# Configuration
EXECUTABLE="./GRTB"
REPORT_FILE="performance_report.md"
# Scenes to benchmark (excluding scene 9 as it is usually too slow for quick tests)
SCENES=(1 2 3 4 5 6 7 8 10)

# Initialize Markdown file
echo "# 🚀 Performance Report - $(date +'%Y-%m-%d %H:%M')" >$REPORT_FILE
echo "" >>$REPORT_FILE
echo "**System Info:** $(uname -sm)" >>$REPORT_FILE
echo "" >>$REPORT_FILE
echo "| Scene | Real Time (Total) | User Time (CPU) |" >>$REPORT_FILE
echo "| :--- | :--- | :--- |" >>$REPORT_FILE

echo "Starting Benchmark..."

for SCENE in "${SCENES[@]}"; do
    echo "Benchmarking Scene $SCENE..."

    # Run the executable and capture the output of /usr/bin/time
    # -p flag ensures POSIX output format (real, user, sys)
    STATS=$({ /usr/bin/time -p "$EXECUTABLE" "$SCENE" >/dev/null; } 2>&1)

    # Extract values using awk
    REAL_TIME=$(echo "$STATS" | grep real | awk '{print $2}')
    USER_TIME=$(echo "$STATS" | grep user | awk '{print $2}')

    # Append the results to the Markdown table
    echo "| Scene $SCENE | ${REAL_TIME}s | ${USER_TIME}s |" >>$REPORT_FILE
done

echo "" >>$REPORT_FILE
echo "---" >>$REPORT_FILE
echo "### Legend" >>$REPORT_FILE
echo "- **Real Time**: The actual wall-clock time elapsed during the execution." >>$REPORT_FILE
echo "- **User Time**: The total amount of time spent in user-mode code (sum of all CPU cores)." >>$REPORT_FILE
echo "" >>$REPORT_FILE
echo "*Generated by automated benchmark script.*" >>$REPORT_FILE

echo "✅ Report generated: $REPORT_FILE"
